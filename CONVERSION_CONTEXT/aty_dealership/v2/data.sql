CREATE TABLE IF NOT EXISTS `aty_dealership` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `owner` varchar(55) DEFAULT NULL,
  `name` varchar(50) DEFAULT NULL,
  `type` varchar(50) DEFAULT NULL,
  `job` varchar(50) DEFAULT 'all',
  `orders` longtext DEFAULT '{}',
  `vehicles` longtext DEFAULT NULL,
  `sales` longtext DEFAULT NULL,
  `locations` longtext DEFAULT NULL,
  `listings` longtext DEFAULT '{}',
  `coupons` longtext DEFAULT '{}',
  `price` int(11) DEFAULT NULL,
  `status` int(11) DEFAULT 1,
  `balance` int(11) DEFAULT 0,
  `blip` int(11) DEFAULT 100,
  `pedModel` varchar(50) DEFAULT NULL,
  `employees` longtext DEFAULT '[]',
  `ranks` longtext DEFAULT '[]',
  PRIMARY KEY (`id`),
  KEY `owner` (`owner`)
) ENGINE=InnoDB AUTO_INCREMENT=20 DEFAULT CHARSET=utf8 COLLATE=utf8_general_ci;

CREATE TABLE IF NOT EXISTS `vehicle_installments` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `citizenid` varchar(50) NOT NULL,
  `vehicle_model` varchar(50) NOT NULL,
  `vehicle_label` varchar(50) DEFAULT NULL,
  `plate` varchar(50) NOT NULL,
  `dealership_id` int(11) DEFAULT NULL,
  `total_amount` int(11) NOT NULL,
  `remaining_amount` int(11) NOT NULL,
  `monthly_payment` int(11) NOT NULL,
  `remaining_months` int(11) NOT NULL,
  `next_payment_date` datetime DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `citizenid` (`citizenid`),
  KEY `dealership_id` (`dealership_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
